import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

export async function sources(root) {
  const directory = path.join(root, 'src/OCFoundation');
  const names = (await readdir(directory)).filter(name => name.endsWith('.luau')).sort();
  const modules = await Promise.all(names.map(async filename => ({
    name: filename.slice(0, -5),
    source: (await readFile(path.join(directory, filename), 'utf8')).replace(/\r\n/g, '\n'),
  })));
  const entry = (await readFile(path.join(root, 'src/OC.luau'), 'utf8')).replace(/\r\n/g, '\n');
  return { modules, entry };
}

export function bundle({ modules, entry }) {
  const buildId = createHash('sha256').update(JSON.stringify({ modules, entry })).digest('hex').slice(0, 12);
  const names = new Set(modules.map(module => module.name));
  function transform(source) {
    const transformed = source.replace(/require\(script\.Parent\.(?:OCFoundation\.)?(\w+)\)/g, (match, name) => {
      if (!names.has(name)) throw new Error(`Unresolved OC import: ${match}`);
      return `requireOC("${name}")`;
    }).replaceAll('__OC_BUILD_ID__', buildId);
    if (/\bscript\./.test(transformed)) throw new Error('Standalone source still depends on a Script instance');
    return transformed;
  }
  const prelude = `--!nonstrict
-- GENERATED by node scripts/build.mjs. Edit src/, then rebuild.
-- Phase 2: Intelligent Island Farming, Bulk Collection Fallback, Bubbles and Upgrades.
-- Build: ${buildId}
local factories, cache, loading = {}, {}, {}
local function requireOC(name)
  if cache[name] ~= nil then return cache[name] end
  assert(factories[name], "[OC] Unknown bundled module: " .. tostring(name))
  assert(not loading[name], "[OC] Circular bundled dependency: " .. tostring(name))
  loading[name] = true
  local ok, result = pcall(factories[name])
  loading[name] = nil
  if not ok then error("[OC] Module " .. name .. " failed: " .. tostring(result), 0) end
  cache[name] = result
  return result
end
`;
  const library = prelude + modules.map(module => `\n-- src/OCFoundation/${module.name}.luau\nfactories["${module.name}"] = function()\n${transform(module.source)}\nend\n`).join('');
  const output = library + `\n-- src/OC.luau\nlocal function entry()\n${transform(entry)}\nend\nreturn entry()\n`;
  return { output, library, buildId };
}
