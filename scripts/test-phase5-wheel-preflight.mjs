// Executes the owner preflight loader against the published candidate's real
// GameKnowledge observer and offline account fixtures. No network/game actions.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync, spawnSync } from 'node:child_process';
import path from 'node:path';
import { bundle, sources } from './bundle.mjs';
import { verifyFreeWheelTicketWorkspace } from './verify-phase5-free-wheel-ticket.mjs';

const root = path.resolve(import.meta.dirname, '..');
verifyFreeWheelTicketWorkspace();
const source = await sources(root);
const generated = bundle(source);
const pinnedBundle = execFileSync('git', ['show', 'phase5-free-wheel-ticket-668d0af6f157:dist/OC.lua'], { cwd: root, maxBuffer: 16 * 1024 * 1024 }).toString('utf8');
assert(pinnedBundle.includes('-- Build: 668d0af6f157'), 'Execute the preserved candidate used by the actual owner loader');
const pinnedLibrary = pinnedBundle.split('\n-- src/OC.luau\n')[0];
assert(pinnedLibrary.length < pinnedBundle.length, 'Separate the unchanged candidate library from its Roblox bootstrap');
const bundlePath = path.join(root, 'dist/OC.lua');
const before = await readFile(bundlePath);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const environment = (await readFile(path.join(root, 'tests/foundation.luau'), 'utf8')).split('-- BUNDLE INSERTION POINT')[0];
const wheelFixture = await readFile(path.join(root, 'tests/phase5-free-wheel-ticket.luau'), 'utf8');
const fixturePrefix = wheelFixture.slice(0, wheelFixture.indexOf('audit("actual native observation'));
assert(fixturePrefix.includes('local function knowledgeFixture()'), 'Reuse actual native account/observer fixture');
const loaderPath = path.join(root, 'examples/Phase5FreeWheelTicketPreflight.luau');
const loader = await readFile(loaderPath, 'utf8');
const url = 'https://raw.githubusercontent.com/Whispfl/automation-/phase5-free-wheel-ticket-668d0af6f157/dist/OC.lua';
const loadCall = `local OC = loadstring(game:HttpGet("${url}"))()(Config)`;
assert(loader.includes(loadCall), 'Owner preflight fetches the existing immutable candidate');
assert.equal((loader.match(/game:HttpGet\(/g) || []).length, 1, 'Preflight has only one public bundle fetch');
assert(!/\b(?:GitHubToken|FireServer|InvokeServer)\b|["']Authorization["']\s*[:=]/.test(loader), 'Owner loader has no credentials or action transport');
assert(!/:\s*(?:Start|Select|Prepare|PrepareFreeWheelTicket|RewardAction|ClaimFreeWheelTicket|MarkFreeWheelTicketDispatched|ObserveFreeWheelTicket|InitializeFreeWheelTicketLedger)\s*\(/.test(loader), 'Read-only preflight does not enter execution or ledger-mutating methods');
const executableLoader = loader.replace(loadCall, 'local OC = wheelPreflightMockLoad(Config)');
await mkdir(path.join(root, '.test-output'), { recursive: true });
const file = path.join(root, '.test-output/phase5-wheel-preflight.luau');
const tests = await readFile(path.join(root, 'tests/phase5-wheel-preflight.luau'), 'utf8');
await writeFile(file, `${environment}\nlocal shared = {}\n${pinnedLibrary}\n${fixturePrefix}\nlocal wheelPreflightScene\nlocal function wheelPreflightMockLoad(config)\n return wheelPreflightScene:Load(config)\nend\nlocal function executeWheelPreflightLoader()\n${executableLoader}\nend\n${tests}`);
const compiler = process.env.LUAU_COMPILE_BIN || path.join(root, '.tools/luau', process.platform === 'win32' ? 'luau-compile.exe' : 'luau-compile');
const executable = process.env.LUAU_BIN || path.join(root, '.tools/luau', process.platform === 'win32' ? 'luau.exe' : 'luau');
const compile = spawnSync(compiler, ['--null', loaderPath, file], { encoding: 'utf8' });
if (compile.error) throw compile.error;
assert.equal(compile.status, 0, compile.stdout + compile.stderr);
const run = spawnSync(executable, [file], { encoding: 'utf8' });
if (run.error) throw run.error;
process.stdout.write(run.stdout || '');
process.stderr.write(run.stderr || '');
assert.equal(run.status, 0, 'Actual owner preflight loader and preserved native observer suite must pass');
assert.equal(hash(await readFile(bundlePath)), hash(before), 'Preflight tests leave the published bundle byte-identical');
assert.equal(bundle(await sources(root)).buildId, generated.buildId, 'Preflight tests leave all gameplay source identical');
console.log('[OC WHEEL PREFLIGHT] Official Luau compilation PASS; actual disabled loader/read-only observer PASS; existing candidate unchanged; live claim remains unapproved.');
